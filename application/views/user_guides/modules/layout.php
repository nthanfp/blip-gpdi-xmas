             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-info-circle mr-2"></i>Ringkasan</div>
                 <div class="guide-section-body">
                     <p>Menu Seating Layout menampilkan denah kursi seluruh lantai (Floor 1 &amp; Floor 2) dengan status real-time dari database. Dari sini admin menentukan kursi fisik per registrasi (jemaat) maupun per booking/undangan.</p>
                 </div>
             </div>
             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-palette mr-2"></i>Warna Kursi (Legend)</div>
                 <div class="guide-section-body">
                     <p class="mb-1"><span class="badge badge-light border">1</span> <strong>Available</strong> — kursi kosong &nbsp;·&nbsp; <span class="badge badge-success">Hijau</span> <strong>Confirmed</strong> — sudah terisi jemaat &nbsp;·&nbsp; <span class="badge badge-warning">Oranye</span> <strong>Selected</strong> — sedang dipilih</p>
                     <p class="mb-0"><span class="badge badge-primary">Biru</span> <strong>Reserved</strong> — ditahan Booking &amp; Undangan &nbsp;·&nbsp; <span class="badge badge-dark">Hitam</span> Meja/Pilar &nbsp;·&nbsp; Outline merah = milik registrasi/booking aktif (siap release)</p>
                 </div>
             </div>
             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-list-ol mr-2"></i>Cara Penggunaan</div>
                 <div class="guide-section-body">
                     <div class="guide-step">
                         <div class="step-num">1</div>
                         <div class="step-body"><strong>Mode Registration</strong>
                             <p>Cari registrasi (kode 5 karakter / HP / nama) → centang peserta <em>Confirmed</em> → klik kursi kosong di denah (jumlah harus sama) → klik <em>Assign</em>. Klik kursi ber-outline merah milik registrasi ini untuk memilih lalu <em>Release</em>.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">2</div>
                         <div class="step-body"><strong>Mode Booking</strong>
                             <p>Klik tab <em>Booking</em> → cari undangan (nama/floor/ID) → klik kursi kosong untuk <em>Reserve</em> (maksimal sejumlah kursi booking) atau klik kursi biru milik booking tersebut lalu <em>Release</em>.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">3</div>
                         <div class="step-body"><strong>Aturan penting</strong>
                             <p>Peserta berstatus <em>Pending</em> belum bisa dipilih — confirm dulu di menu Pendaftaran. Kursi yang sudah di-reserve booking tidak bisa dipakai registrasi, dan sebaliknya (saling terkunci).</p>
                         </div>
                     </div>
                 </div>
             </div>
             <div class="guide-tip"><i class="fas fa-lightbulb mr-2"></i><strong>Tips:</strong> Penomoran kursi mengikuti pola snake (baris bolak-balik). Hover kursi untuk melihat nomor beserta nama/kode registrasinya.</div>
