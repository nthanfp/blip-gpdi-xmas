             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-info-circle mr-2"></i>Ringkasan</div>
                 <div class="guide-section-body">
                     <p>Menu Pendaftaran Natal adalah pusat data pendaftar event: melihat statistik sisa kuota per lantai, mengelola status kehadiran (confirm/cancel) per registrasi maupun per orang, mengatur kuota lantai, serta melihat detail kursi yang sudah di-assign.</p>
                 </div>
             </div>
             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-list-ol mr-2"></i>Cara Penggunaan</div>
                 <div class="guide-section-body">
                     <div class="guide-step">
                         <div class="step-num">1</div>
                         <div class="step-body"><strong>Pilih tampilan</strong>
                             <p><em>Individual</em> (default) menampilkan baris per jemaat; <em>Group</em> menampilkan baris per pendaftaran (kode, telepon, jumlah orang).</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">2</div>
                         <div class="step-body"><strong>Filter &amp; cari</strong>
                             <p>Gunakan Search (kode/telepon/nama), filter Floor dan Status (Pending/Confirmed/Cancelled), lalu klik Apply.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">3</div>
                         <div class="step-body"><strong>Confirm / Cancel peserta</strong>
                             <p>Klik ikon ✔ untuk konfirmasi atau ✖ untuk membatalkan. Pada tampilan Group, muncul dialog untuk memilih peserta mana yang diproses. Membatalkan peserta akan otomatis melepas kursi yang sudah ter-assign.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">4</div>
                         <div class="step-body"><strong>Detail &amp; hapus</strong>
                         <p>Ikon 👁 membuka detail (daftar peserta, umur, status, kursi). Ikon 🗑 menghapus registrasi beserta seluruh pesertanya (konfirmasi dulu).</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">5</div>
                         <div class="step-body"><strong>Set Quota</strong>
                             <p>Tombol <em>Set Quota</em> mengubah kapasitas kursi per lantai. Kapasitas tidak boleh di bawah jumlah peserta terdaftar + kursi yang ditahan Booking.</p>
                         </div>
                     </div>
                 </div>
             </div>
             <div class="guide-tip"><i class="fas fa-lightbulb mr-2"></i><strong>Tips:</strong> Info-box atas menampilkan <em>Sisa / Kapasitas Seats</em> per lantai, termasuk jumlah <span class="text-warning">booked</span> (kursi yang ditahan menu Booking &amp; Invitation). Angka sisa yang sama juga tampil di form pendaftaran publik.</div>
