                <div class="guide-section-header"><i class="fas fa-info-circle mr-2"></i>Ringkasan</div>
                <div class="guide-section-body">
                    <p class="mb-0">Module API Key digunakan untuk mengelola API key yang digunakan oleh sistem eksternal untuk autentikasi. Setiap API key memiliki nama, key value, catatan, dan status aktif.</p>
                </div>
            </div>
            <div class="guide-section">
                <div class="guide-section-header"><i class="fas fa-list-ol mr-2"></i>Cara Penggunaan</div>
                <div class="guide-section-body">
                    <div class="guide-step">
                        <div class="step-num">1</div>
                        <div class="step-body"><strong>Tambah API Key baru</strong>
                            <p>Klik + NEW. Isi Key Name dan Notes. Key value akan di-generate otomatis oleh sistem.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">2</div>
                        <div class="step-body"><strong>Edit API Key</strong>
                            <p>Klik ikon edit untuk mengubah Key Name, Notes, atau mengaktifkan/menonaktifkan API key.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">3</div>
                        <div class="step-body"><strong>Regenerate Key</strong>
                            <p>Klik ikon regenerate untuk membuat key value baru. Key lama akan langsung tidak berlaku. Pastikan sistem eksternal sudah diperbarui.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">4</div>
                        <div class="step-body"><strong>Hapus API Key</strong>
                            <p>Klik ikon hapus untuk menghapus API key secara permanen. Pastikan key tidak lagi digunakan oleh sistem eksternal.</p>
                        </div>
                    </div>
                </div>
            </div>
