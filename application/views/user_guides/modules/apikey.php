            <div class="guide-section">
                <div class="guide-section-header"><i class="fas fa-info-circle mr-2"></i>Ringkasan</div>
                <div class="guide-section-body">
                    <p class="mb-0">Module API Key digunakan untuk mengelola kunci autentikasi API. Setiap key memiliki nama, catatan, status aktif/nonaktif, dan nilai kunci unik yang digunakan oleh sistem eksternal untuk mengakses API.</p>
                </div>
            </div>
            <div class="guide-section">
                <div class="guide-section-header"><i class="fas fa-list-ol mr-2"></i>Cara Penggunaan</div>
                <div class="guide-section-body">
                    <div class="guide-step">
                        <div class="step-num">1</div>
                        <div class="step-body"><strong>Buat API Key baru</strong>
                            <p>Klik + NEW. Isi Key Name dan Notes. Klik Save untuk membuat key baru. Nilai key akan digenerate otomatis.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">2</div>
                        <div class="step-body"><strong>Regenerate Key</strong>
                            <p>Jika key perlu di-refresh, klik ikon regenerate. Key lama akan invalid dan key baru dihasilkan.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">3</div>
                        <div class="step-body"><strong>Aktifkan / Nonaktifkan</strong>
                            <p>Edit key dan ubah status is_active untuk menonaktifkan akses tanpa menghapus key.</p>
                        </div>
                    </div>
                    <div class="guide-step">
                        <div class="step-num">4</div>
                        <div class="step-body"><strong>Hapus Key</strong>
                            <p>Klik ikon delete untuk menghapus key secara permanen. Tindakan ini tidak dapat dibatalkan.</p>
                        </div>
                    </div>
                </div>
            </div>
            <div class="guide-tip"><i class="fas fa-lightbulb mr-2"></i><strong>Tips:</strong> Simpan nilai key dengan aman setelah dibuat. Regenerate hanya jika key terkompromi.</div>
