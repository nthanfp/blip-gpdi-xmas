             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-info-circle mr-2"></i>Ringkasan</div>
                 <div class="guide-section-body">
                     <p>Menu <strong>Booking &amp; Invitation</strong> menahan kuota kursi per lantai untuk tamu undangan (panitia, narasumber, tamu undangan) sekaligus menjadi halaman undangan pribadi. Kursi yang ditahan mengurangi sisa kuota pendaftaran publik, dan penentuan kursi fisiknya dilakukan di menu Seating Layout.</p>
                 </div>
             </div>
             <div class="guide-section">
                 <div class="guide-section-header"><i class="fas fa-list-ol mr-2"></i>Cara Penggunaan</div>
                 <div class="guide-section-body">
                     <div class="guide-step">
                         <div class="step-num">1</div>
                         <div class="step-body"><strong>Tambah booking/undangan</strong>
                             <p>Klik <em>+ New</em>, isi <em>Name</em> (wajib), <em>Phone</em> (opsional), <em>Floor</em>, <em>Number of Seats</em>, dan <em>Notes</em>. Jumlah kursi tidak boleh melebihi sisa kuota lantai.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">2</div>
                         <div class="step-body"><strong>Bagikan link undangan</strong>
                             <p>Klik ikon 🌐 pada baris → membuka halaman <code>/invitation/{id}</code> di tab baru. Link ini dibagikan ke tamu; di sana tamu mengisi konfirmasi jumlah orang yang hadir (maksimal sejumlah kursi booking).</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">3</div>
                         <div class="step-body"><strong>Tentukan kursi fisik</strong>
                             <p>Buka <strong>Seating Layout</strong> → tab <em>Booking</em> → cari undangan → klik kursi kosong → <em>Reserve</em>. Kursi jadi berwarna biru dan terkunci dari registrasi publik.</p>
                         </div>
                     </div>
                     <div class="guide-step">
                         <div class="step-num">4</div>
                         <div class="step-body"><strong>Edit / Batalkan / Hapus</strong>
                         <p>Status <em>Cancelled</em> otomatis melepas semua kursi reserved dan mengembalikan kuota; mengurangi jumlah kursi di bawah jumlah yang sudah di-assign akan ditolak; menghapus booking juga melepas kursinya.</p>
                         </div>
                     </div>
                 </div>
             </div>
             <div class="guide-tip"><i class="fas fa-lightbulb mr-2"></i><strong>Tips:</strong> Badge <span class="badge badge-success">✓ N</span> di kolom Name menunjukkan jumlah tamu yang sudah mengonfirmasi kehadiran lewat link undangan. Total booked tampil di info-box dan di menu Pendaftaran.</div>
