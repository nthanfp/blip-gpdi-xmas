  floor_id INT UNSIGNED NOT NULL,
  row_id INT UNSIGNED NOT NULL,
  seat_number INT UNSIGNED NOT NULL,
  attendeeid BIGINT NULL,
  registrationid BIGINT NULL,
  assigned_by INT UNSIGNED NULL,
  assigned_date DATETIME(6) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_seating_seat (floor_id, seat_number),
  KEY idx_seating_seat_attendee (attendeeid),
  KEY idx_seating_seat_reg (registrationid),
  CONSTRAINT fk_seating_seat_floor FOREIGN KEY (floor_id)
    REFERENCES act_seating_floor (id),
  CONSTRAINT fk_seating_seat_row FOREIGN KEY (row_id)
    REFERENCES act_seating_row (id),
  CONSTRAINT fk_seating_seat_attendee FOREIGN KEY (attendeeid)
    REFERENCES act_xmas_attendee (attendeeid) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

